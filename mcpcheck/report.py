"""Render conformance and fuzz results."""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

from .checks import ERROR, FAIL, INFO, PASS, SKIP, WARNING, CheckResult
from .fuzz import BAD, OK, WEAK, FuzzResult

STATUS_MARK = {PASS: "pass", FAIL: "FAIL", SKIP: "skip"}
OUTCOME_MARK = {OK: "ok", WEAK: "weak", BAD: "BAD"}


@dataclass
class Report:
    target: str
    checks: List[CheckResult] = field(default_factory=list)
    fuzz: List[FuzzResult] = field(default_factory=list)

    @property
    def errors_failed(self) -> int:
        return sum(1 for check in self.checks if check.severity == ERROR and check.status == FAIL)

    @property
    def warnings_failed(self) -> int:
        return sum(
            1 for check in self.checks if check.severity == WARNING and check.status == FAIL
        )

    @property
    def checks_passed(self) -> int:
        return sum(1 for check in self.checks if check.status == PASS)

    @property
    def checks_skipped(self) -> int:
        return sum(1 for check in self.checks if check.status == SKIP)

    @property
    def fuzz_bad(self) -> int:
        return sum(1 for result in self.fuzz if result.outcome == BAD)

    @property
    def fuzz_weak(self) -> int:
        return sum(1 for result in self.fuzz if result.outcome == WEAK)

    @property
    def ok(self) -> bool:
        return self.errors_failed == 0 and self.fuzz_bad == 0

    def as_dict(self) -> Dict[str, Any]:
        return {
            "target": self.target,
            "ok": self.ok,
            "summary": {
                "checks": len(self.checks),
                "checks_passed": self.checks_passed,
                "checks_skipped": self.checks_skipped,
                "errors_failed": self.errors_failed,
                "warnings_failed": self.warnings_failed,
                "fuzz_cases": len(self.fuzz),
                "fuzz_bad": self.fuzz_bad,
                "fuzz_weak": self.fuzz_weak,
            },
            "checks": [check.as_dict() for check in self.checks],
            "fuzz": [result.as_dict() for result in self.fuzz],
        }


def render_markdown(report: Report, title: str = "MCP conformance report") -> str:
    lines: List[str] = []
    lines.append("# %s" % title)
    lines.append("")
    lines.append("**Target:** `%s`  " % report.target)
    lines.append(
        "**Result:** %s" % ("pass" if report.ok else "FAIL")
    )
    lines.append("")

    lines.append("| metric | value |")
    lines.append("| --- | --- |")
    lines.append("| checks run | %d |" % len(report.checks))
    lines.append("| checks passed | %d |" % report.checks_passed)
    lines.append("| checks skipped | %d |" % report.checks_skipped)
    lines.append("| error-severity failures | %d |" % report.errors_failed)
    lines.append("| warning-severity failures | %d |" % report.warnings_failed)
    if report.fuzz:
        lines.append("| fuzz cases | %d |" % len(report.fuzz))
        lines.append("| fuzz crashes or hangs | %d |" % report.fuzz_bad)
        lines.append("| fuzz weak responses | %d |" % report.fuzz_weak)
    lines.append("")

    if report.checks:
        lines.append("## Checks")
        lines.append("")
        lines.append("| check | severity | result | detail |")
        lines.append("| --- | --- | --- | --- |")
        for check in report.checks:
            detail = check.detail.replace("|", "\\|")
            lines.append(
                "| `%s` | %s | %s | %s |"
                % (check.id, check.severity, STATUS_MARK[check.status], detail)
            )
        lines.append("")

    failures = [check for check in report.checks if check.status == FAIL]
    if failures:
        lines.append("## Failures")
        lines.append("")
        for check in failures:
            lines.append("### `%s` — %s" % (check.id, check.title))
            lines.append("")
            lines.append("- severity: %s" % check.severity)
            lines.append("- %s" % check.detail)
            lines.append("")

    if report.fuzz:
        lines.append("## Fuzz")
        lines.append("")
        lines.append("| case | result | detail |")
        lines.append("| --- | --- | --- |")
        for result in report.fuzz:
            detail = result.detail.replace("|", "\\|")
            lines.append(
                "| `%s` | %s | %s |" % (result.id, OUTCOME_MARK[result.outcome], detail)
            )
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append(
        "Generated by [mcpcheck](https://github.com/Coisini-cyber/mcpcheck). "
        "Checks follow the Model Context Protocol specification; a pass is not a "
        "security review."
    )
    lines.append("")
    return "\n".join(lines)


def render_json(report: Report) -> str:
    return json.dumps(report.as_dict(), indent=2, ensure_ascii=False) + "\n"


def render_console(report: Report) -> str:
    lines: List[str] = []
    for check in report.checks:
        lines.append(
            "%-4s %-9s %-34s %s"
            % (STATUS_MARK[check.status], check.severity, check.id, check.detail)
        )
    if report.fuzz:
        lines.append("")
        for result in report.fuzz:
            lines.append(
                "%-4s %-34s %s" % (OUTCOME_MARK[result.outcome], result.id, result.detail)
            )
    lines.append("")
    verdict = "PASS" if report.ok else "FAIL"
    lines.append(
        "%s: %d checks, %d error failures, %d warning failures, %d fuzz failures"
        % (verdict, len(report.checks), report.errors_failed, report.warnings_failed, report.fuzz_bad)
    )
    return "\n".join(lines)
